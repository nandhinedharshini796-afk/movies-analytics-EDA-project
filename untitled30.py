import os
import zipfile
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

zip_path = "/content/archive (1).zip"
csv_path = "tmdb_data/tmdb_5000_movies.csv"

# Load df if not already defined in memory
if "df" not in globals():
    if not os.path.exists(csv_path):
        if os.path.exists(zip_path):
            with zipfile.ZipFile(zip_path, "r") as z:
                z.extractall("tmdb_data")
        else:
            raise FileNotFoundError(f"'{zip_path}' not found.")
    df = pd.read_csv(csv_path)

# EDA question 4: Which numeric features are most correlated with revenue?
num_df = df.select_dtypes(include="number")
if "revenue" in num_df.columns:
    rev_corr = num_df.corr()["revenue"].sort_values(ascending=False)
    print("Correlation with revenue:")
    display(rev_corr)

# EDA question 5: Visualize budget vs revenue colored by top 5 original languages
if {"budget", "revenue", "original_language"}.issubset(df.columns):
    top_langs = df["original_language"].value_counts().head(5).index
    plot_df = df[
        (df["budget"] > 0)
        & (df["revenue"] > 0)
        & (df["original_language"].isin(top_langs))
    ].copy()

    if not plot_df.empty:
        sample_df = plot_df.sample(min(5000, len(plot_df)), random_state=42)
        plt.figure(figsize=(10, 7))
        sns.scatterplot(
            data=sample_df,
            x="budget",
            y="revenue",
            hue="original_language",
            s=18,
            alpha=0.6,
        )
        plt.title("Sampled TMDB Movies: Budget vs Revenue by Top 5 Languages")
        plt.xlabel("Budget (USD)")
        plt.ylabel("Revenue (USD)")
        plt.legend(title="Language", bbox_to_anchor=(1.02, 1), loc="upper left")
        plt.tight_layout()
        plt.show()